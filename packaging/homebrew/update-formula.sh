#!/usr/bin/env bash
# Regenerate the Homebrew formula for a released version.
#
#   ./update-formula.sh 0.2.0            # reads checksums from the GitHub release
#   ./update-formula.sh 0.2.0 /tmp/sums  # or from a directory of .sha256 files
#
# The formula is generated rather than hand-edited so that a release cannot
# leave the version and the four checksums disagreeing. CI runs this on a tag
# and pushes the result to the tap; running it locally produces the same file.
set -euo pipefail

version="${1:?usage: update-formula.sh VERSION [SUMS_DIR]}"
version="${version#v}"
repo="Forsbakk/solitaire-tui"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
formula="$here/Formula/solitaire-tui.rb"

# One trap for both temporaries — a second `trap ... EXIT` would replace this
# one rather than add to it.
tmp=''
scratch=''
cleanup() {
  [[ -n "$tmp" ]] && rm -f "$tmp"
  [[ -n "$scratch" ]] && rm -rf "$scratch"
  return 0
}
trap cleanup EXIT

sums_dir="${2:-}"
if [[ -z "$sums_dir" ]]; then
  scratch="$(mktemp -d)"
  sums_dir="$scratch"
  gh release download "v$version" -R "$repo" -p '*.sha256' -D "$sums_dir" >/dev/null
fi

targets=(
  aarch64-apple-darwin
  x86_64-apple-darwin
  aarch64-unknown-linux-musl
  x86_64-unknown-linux-musl
)

# Each archive ships a sidecar named after it minus the extension, holding
# "<sha256>  <archive>". Read every one up front: a `exit` inside the command
# substitution below would only leave the subshell, and the formula would be
# written with empty checksums.
#
# An indexed array kept parallel with `targets`, rather than the associative
# array this obviously wants: CI generates the formula on a macOS runner, and
# macOS ships bash 3.2, where `declare -A` does not exist.
sums=()
for t in "${targets[@]}"; do
  f="$sums_dir/solitaire-tui-v$version-$t.sha256"
  [[ -r "$f" ]] || { echo "missing checksum file: $f" >&2; exit 1; }
  sum="$(awk '{print $1}' "$f")"
  [[ $sum =~ ^[0-9a-f]{64}$ ]] || {
    echo "not a sha256 in $f: '$sum'" >&2; exit 1
  }
  sums+=("$sum")
done

# Safe to call from the heredoc below: every sum was validated above, so this
# only ever hands back something already known to be good.
sum_for() {
  local i
  for i in "${!targets[@]}"; do
    if [[ ${targets[$i]} == "$1" ]]; then
      echo "${sums[$i]}"
      return 0
    fi
  done
  echo "no such target: $1" >&2
  return 1
}

url_for() {
  echo "https://github.com/$repo/releases/download/v$version/solitaire-tui-v$version-$1.tar.gz"
}

# Written to a temporary file and moved into place, so a failure part-way
# through cannot leave a half-formed formula behind.
mkdir -p "$here/Formula"
tmp="$(mktemp)"
cat > "$tmp" <<EOF
# Generated by packaging/homebrew/update-formula.sh — do not edit by hand.
#
# Prebuilt binaries rather than a source build: the release workflow already
# produces one per platform, and installing them needs no Rust toolchain.
# The macOS binaries are built on macOS runners, so the native linker has
# ad-hoc signed them and Apple Silicon will run them.
class SolitaireTui < Formula
  desc "Eight solitaire games in the terminal, built with ratatui"
  homepage "https://github.com/$repo"
  version "$version"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$(url_for aarch64-apple-darwin)"
      sha256 "$(sum_for aarch64-apple-darwin)"
    end
    on_intel do
      url "$(url_for x86_64-apple-darwin)"
      sha256 "$(sum_for x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "$(url_for aarch64-unknown-linux-musl)"
      sha256 "$(sum_for aarch64-unknown-linux-musl)"
    end
    on_intel do
      url "$(url_for x86_64-unknown-linux-musl)"
      sha256 "$(sum_for x86_64-unknown-linux-musl)"
    end
  end

  def install
    bin.install "solitaire-tui"
    doc.install "README.md"
  end

  test do
    # The game needs a terminal, so --version is the only thing worth asserting
    # on; it is enough to prove the right architecture's binary was installed.
    assert_match "solitaire-tui #{version}", shell_output("#{bin}/solitaire-tui --version")
  end
end
EOF

mv "$tmp" "$formula"
tmp=''

echo "wrote $formula (version $version)"
